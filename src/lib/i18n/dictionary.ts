/** Widen literal types (from `as const`) to their base types so both
 *  locales share one structural type. Arrays stay readonly (read-only UI). */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : { -readonly [K in keyof T]: Widen<T[K]> };

export type Dictionary = Widen<(typeof dictionary)["en"]>;
